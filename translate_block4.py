count = 0
not_found = []
for name, spanish in translations.items():
    pattern = r'(<string name="' + re.escape(name) + r'"[^>]*>)[^<]*(</string>)'
    new_text = r'\1' + spanish + r'\2'
    new_s, n = re.subn(pattern, new_text, s)
    if n > 0:
        s = new_s
        count += 1
    else:
        not_found.append(name)

open(p, 'w', encoding='utf-8').write(s)
