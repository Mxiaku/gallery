s = open(p, encoding='utf-8').read()

count = 0
for name, spanish in translations.items():
    # Find the string entry with this name (may have English text already)
    # Match: <string name="name" ...>English text</string>
    pattern = r'(<string name="' + re.escape(name) + r'"[^>]*>)[^<]*(</string>)'
    new_text = r'\1' + spanish + r'\2'
    new_s, n = re.subn(pattern, new_text, s)
    if n > 0:
        s = new_s
        count += 1
    else:
        print(f"WARNING: Could not find entry for {name}")

open(p, 'w', encoding='utf-8').write(s)
